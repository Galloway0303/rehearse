const tables: Record<Locale, Dict> = { en, zh }

export function t(locale: Locale, key: string): string {
  return tables[locale][key] ?? tables.en[key] ?? key
}

export function levelLabel(locale: Locale, level: number): string {
  return t(locale, `level${level}`)
}

export function levelDesc(locale: Locale, level: number): string {
  return t(locale, `level${level}Desc`)
}
